/** Masque le nom d'utilisateur : `C:\Users\marie\…` → `%USERPROFILE%\…`. */
export function anonymize(path: string): string {
  return path.replace(/^[A-Za-z]:\\Users\\(?!Public\\|Default\\)[^\\]+(?=\\|$)/i, "%USERPROFILE%");
}

const date = (secs: number) => (secs > 0 ? new Date(secs * 1000).toISOString().slice(0, 10) : "");
const cell = (s: string) => s.replace(/\|/g, "\\|");
const table = (head: string[], rows: string[][]) =>
  [`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.map(cell).join(" | ")} |`)].join("\n");

export type ReportInput = {
  scan: ScanResult;
  cleaners: Cleaner[];
  estimates: CleanReport[];
  elevated: boolean;
  programs: Program[];
  lang: Lang;
  now?: Date;
};

export function buildReport({ scan, cleaners, estimates, elevated, programs, lang, now = new Date() }: ReportInput): string {
  const t = T[lang];
  const b = (n: number) => formatBytes(n, lang);
  const est = new Map(estimates.map((e) => [e.id, e]));
  const items = (list: Item[]) => list.map((i) => [b(i.size), date(i.modified), anonymize(i.path)]);

  const cleanupRows = cleaners
    .map((c) => ({ c, r: est.get(c.id) }))
    .filter(({ c, r }) => (r ? r.bytes > 0 : c.admin && !elevated))
    .sort((x, y) => (y.r?.bytes ?? 0) - (x.r?.bytes ?? 0))
    .map(({ c, r }) => [c.label[lang], r ? b(r.bytes) : t.unknown, c.effect[lang], c.admin ? t.yes : ""]);

  return [
    `# ${t.title} — ${now.toISOString().slice(0, 10)}`,
    `## ${t.prompt}`,
    PROMPT[lang],
    `## ${t.summary}`,
    [
      `- ${t.drives} : ${scan.roots.join(", ")}`,
      `- ${t.total} : ${b(scan.bytes)}`,
      `- ${t.files} : ${scan.files}`,
      `- ${t.denied} : ${scan.denied}`,
    ].join("\n"),
    `## ${t.types}`,
    table(
      [t.cols.item, t.cols.size],
      [...scan.categories].sort((x, y) => y.bytes - x.bytes).map((c) => [t.cat[c.category as Category], b(c.bytes)]),
    ),
    `## ${t.cleanups}`,
    table([t.cols.item, t.cols.size, t.cols.effect, t.cols.admin], cleanupRows),
    `## ${t.programs}`,
    table(
      [t.cols.name, t.cols.publisher, t.cols.size, t.cols.installed],
      programs.slice(0, 150).map((p) => [p.name, p.publisher, p.bytes > 0 ? b(p.bytes) : "", p.install_date]),
    ),
    `## ${t.dirs}`,
    table([t.cols.size, t.cols.modified, t.cols.path], items(scan.top_dirs)),
    `## ${t.bigFiles}`,
    table([t.cols.size, t.cols.modified, t.cols.path], items(scan.top_files)),
  ].join("\n\n") + "\n";
}
